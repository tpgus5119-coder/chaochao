def texts_needed(prep, ear):
    out = []
    for d in prep:
        for x in d.get("letters", []):
            out += [x.get("snd"), x.get("ex")]
        for c in d.get("cmp", []):
            out += [i["vi"] for i in c["items"]]
        for t in d.get("tones", []):
            out.append(t["vi"])
    for gs in ear.values():
        for g in gs:
            out += [i["vi"] for i in g["items"]]
    seen, res = set(), []
    for t in out:
        if t and t not in seen:
            seen.add(t); res.append(t)
    return res


