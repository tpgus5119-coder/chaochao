JUNG_Y = {2, 6, 7, 12, 17, 20}   # ㅑ ㅕ ㅖ ㅛ ㅠ ㅣ


def dueum(ch):
    """낱말 첫머리 두음법칙 — 락→낙, 력→역, 녀→여"""
    o = ord(ch) - 0xAC00
    if not 0 <= o < 11172: return ch
    cho, jung, jong = o // 588, (o % 588) // 28, o % 28
    if cho == 5: cho = 11 if jung in JUNG_Y else 2          # ㄹ → ㅇ/ㄴ
    elif cho == 2 and jung in JUNG_Y: cho = 11               # ㄴ → ㅇ
    return chr(0xAC00 + cho * 588 + jung * 28 + jong)


def fix_multi(w, h, ko):
    syl = w.lower().split()
    out = list(ko)
    for i, (c, sy) in enumerate(zip(h, syl)):
        v = MULTI.get((c, U.normalize('NFC', sy)))
        if v: out[i] = dueum(v) if i == 0 else v
    return ''.join(out)
